"""A real locator map: where in India (or the world) is this video about?

The first rewrite reels (29 Sep) never showed where the Penna actually runs:
every shot was an AI illustration. This draws an honest inset from the
project's own Natural Earth data (geo/*.geojson) — India's states with the
ones the script names filled in gold, and the named rivers traced in blue —
and flow_stitch composites it onto the scenes right after the hook.

Nothing here is generated by a model, so nothing on it can be misspelt or
misplaced. If no state, river or country in the script matches the data,
there is no inset (never a guessed one).
"""
import json
import math
import os
import re
from pathlib import Path

GEO = Path(__file__).resolve().parent.parent / "geo"
NAVY, GOLD, CREAM = (10, 23, 40), (217, 169, 76), (242, 214, 150)
LAND, EDGE, RIVER = (38, 58, 84), (78, 104, 136), (88, 196, 255)

# Script spelling -> Natural Earth name. Only these rivers are drawn: the data
# also holds rivers called "Dam", "Tel" and "Son" that would match ordinary words.
RIVERS = {
    "penna": "Penner", "pennar": "Penner", "penner": "Penner", "pennaru": "Penner",
    "ganga": "Ganges", "ganges": "Ganges", "godavari": "Godävari", "krishna": "Krishna",
    "kaveri": "Cauvery", "cauvery": "Cauvery", "narmada": "Narmada", "tapi": "Tapi",
    "tapti": "Tapi", "mahanadi": "Mahäna Nadï", "brahmaputra": "Brahmaputra",
    "yamuna": "Yamuna", "chambal": "Chambal", "betwa": "Betwa", "sone": "Son",
    "son river": "Son", "gandak": "Gandak", "ghaghara": "Ghäghara", "ghaghra": "Ghäghara",
    "tungabhadra": "Tungabhadra", "bhima": "Bhima", "wainganga": "Wainganga",
    "indravati": "Indravati", "sutlej": "Sutlej", "beas": "Beas", "ravi": "Ravi",
    "chenab": "Chenab", "jhelum": "Jhelum", "indus": "Indus", "mahi": "Mahi",
    "banas": "Banas", "palar": "Palar", "teesta": "Tista", "tista": "Tista",
    "brahmani": "Brahmani",
}
ALIASES = {"odisha": "Odisha", "orissa": "Odisha", "j&k": "Jammu and Kashmir",
           "kashmir": "Jammu and Kashmir", "pondicherry": "Puducherry", "delhi": "Delhi"}


def _load(name):
    with open(GEO / f"{name}.geojson", encoding="utf-8") as f:
        return json.load(f)["features"]


def _rings(geom):
    c = geom["coordinates"]
    if geom["type"] == "Polygon":
        return [c[0]]
    if geom["type"] == "MultiPolygon":
        return [p[0] for p in c]
    if geom["type"] == "LineString":
        return [c]
    if geom["type"] == "MultiLineString":
        return c
    return []


def _corpus(script_data, topic_spec=None):
    parts = [str((topic_spec or {}).get(k, "")) for k in ("topic", "subject")]
    parts += [str(script_data.get(k, "")) for k in ("title", "upload_title")]
    for s in script_data.get("segments") or []:
        parts += [str(l) for l in (s.get("labels") or [])]
    parts += [str(f) for f in script_data.get("facts") or []]
    parts += [str(m.get("place", "")) for m in script_data.get("map_scenes") or [] if isinstance(m, dict)]
    return " \n ".join(parts)


def match(script_data, topic_spec=None):
    """{'states': [...], 'rivers': [...], 'countries': [...], 'title': str}"""
    text = _corpus(script_data, topic_spec)
    low = text.lower()
    states = sorted({f["properties"]["name"] for f in _load("states")
                     if f["properties"].get("admin") == "India"
                     and re.search(r"\b" + re.escape(f["properties"]["name"].lower()) + r"\b", low)})
    states += [v for k, v in ALIASES.items() if re.search(r"\b" + re.escape(k) + r"\b", low) and v not in states]
    rivers = sorted({v for k, v in RIVERS.items() if re.search(r"\b" + re.escape(k) + r"\b", low)})
    countries = []
    if not states and not rivers:
        countries = sorted({f["properties"]["name"] for f in _load("countries")
                            if f["properties"]["name"] != "India"
                            and re.search(r"\b" + re.escape(f["properties"]["name"].lower()) + r"\b", low)})
    subject = str((topic_spec or {}).get("subject") or script_data.get("title") or "")
    # The subject decides what is highlighted when it names something: a Bihar
    # video mentions where the Sone rises, but Madhya Pradesh is not its subject.
    sl = subject.lower()
    def _in_subject(names, table=None):
        keys = {v: [k for k, vv in (table or {}).items() if vv == v] + [v.lower()] for v in names}
        return [v for v in names if any(re.search(r"\b" + re.escape(k) + r"\b", sl) for k in keys[v])]
    states = _in_subject(states, ALIASES) or states
    rivers = _in_subject(rivers, RIVERS) or rivers
    countries = _in_subject(countries) or countries
    try:
        from stage2_daily_draw import clean_idea_title
        subject = clean_idea_title(subject)
    except Exception:  # noqa: BLE001
        subject = re.sub(r"\(.*?\)|explained!?|#\S+", "", subject, flags=re.I)
    subject = re.sub(r"[^\w\s&'-]", "", subject).strip(" !-|:")
    return {"states": states[:4], "rivers": rivers[:5], "countries": countries[:3],
            "title": _fit_words(subject.upper(), 24)}


def _fit_words(text, n):
    """Cut on a word boundary: 'WHY CYPRUS IS DIVIDED EUROPE' -> 'WHY CYPRUS IS DIVIDED'."""
    words, out = text.split(), ""
    for w in words:
        if len(out) + len(w) + (1 if out else 0) > n:
            break
        out = f"{out} {w}".strip()
    return out or text[:n]


def render(script_data, out_path, frame=(1080, 1920), topic_spec=None):
    """Write the inset PNG (full-frame, transparent) and return its path, or None."""
    m = match(script_data, topic_spec)
    if not (m["states"] or m["rivers"] or m["countries"]):
        return None
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        return None

    fw, fh = frame
    portrait = fh > fw
    cw, ch = (int(fw * 0.44), int(fw * 0.52)) if portrait else (int(fh * 0.42), int(fh * 0.50))
    cx0 = int(fw * 0.04) if portrait else int(fw - cw - fh * 0.04)
    cy0 = int(fh - ch - fh * 0.10) if portrait else int(fh - ch - fh * 0.09)
    head = int(ch * 0.13)

    india = bool(m["states"] or m["rivers"])
    if india:
        base = [f for f in _load("states") if f["properties"].get("admin") == "India"]
        hit = [f for f in base if f["properties"]["name"] in m["states"]]
        hit += [f for f in _load("rivers") if f["properties"].get("name") in m["rivers"]]
        xs = [p[0] for f in hit for r in _rings(f["geometry"]) for p in r if 60 < p[0] < 100 and 5 < p[1] < 38]
        ys = [p[1] for f in hit for r in _rings(f["geometry"]) for p in r if 60 < p[0] < 100 and 5 < p[1] < 38]
        # the region plus neighbours: at least 13 degrees across, so a viewer
        # sees which neighbouring states it sits between
        cxm, cym = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
        half = max(max(xs) - min(xs), (max(ys) - min(ys)) * (cw / max(ch - head, 1)), 13) * 0.62
        lon0, lon1 = cxm - half, cxm + half
        hy = half * (ch - head) / cw / math.cos(math.radians(cym)) * 1.0
        lat0, lat1 = cym - hy, cym + hy
        base = _load("states")      # neighbours outside India are drawn too
    else:
        hit = [f for f in _load("countries") if f["properties"]["name"] in m["countries"]]
        xs = [p[0] for f in hit for r in _rings(f["geometry"]) for p in r]
        ys = [p[1] for f in hit for r in _rings(f["geometry"]) for p in r]
        pad = max(max(xs) - min(xs), max(ys) - min(ys), 4) * 2.5
        lon0, lon1 = (min(xs) + max(xs)) / 2 - pad, (min(xs) + max(xs)) / 2 + pad
        lat0, lat1 = (min(ys) + max(ys)) / 2 - pad, (min(ys) + max(ys)) / 2 + pad
        base = _load("countries")
    k = math.cos(math.radians((lat0 + lat1) / 2))
    mw, mh = cw - 24, ch - head - 20
    scale = min(mw / ((lon1 - lon0) * k), mh / (lat1 - lat0))
    ox = cx0 + 12 + (mw - (lon1 - lon0) * k * scale) / 2
    oy = cy0 + head + 8 + (mh - (lat1 - lat0) * scale) / 2

    def xy(p):
        return (ox + (p[0] - lon0) * k * scale, oy + (lat1 - p[1]) * scale)

    img = Image.new("RGBA", frame, (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((cx0, cy0, cx0 + cw, cy0 + ch), radius=28,
                        fill=NAVY + (228,), outline=GOLD + (255,), width=4)
    # map area is clipped to the card by drawing into a separate layer
    layer = Image.new("RGBA", frame, (0, 0, 0, 0))
    ld = ImageDraw.Draw(layer)
    hl = set(m["states"]) | set(m["countries"])
    for f in base:
        name = f["properties"]["name"]
        fill = (120, 96, 48, 255) if name in hl else LAND + (255,)
        for ring in _rings(f["geometry"]):
            pts = [xy(p) for p in ring]
            if len(pts) > 2:
                ld.polygon(pts, fill=fill, outline=EDGE + (255,))
    if india:
        width = max(5, int(cw / 70))
        for f in _load("rivers"):
            if f["properties"].get("name") in m["rivers"]:
                for line in _rings(f["geometry"]):
                    pts = [xy(p) for p in line]
                    ld.line(pts, fill=NAVY + (255,), width=width + 4, joint="curve")
                    ld.line(pts, fill=RIVER + (255,), width=width, joint="curve")
    # highlighted outlines on top, gold, so borders read against the fill
    for f in base:
        if f["properties"]["name"] in hl:
            for ring in _rings(f["geometry"]):
                pts = [xy(p) for p in ring]
                if len(pts) > 2:
                    ld.line(pts + pts[:1], fill=GOLD + (255,), width=3)
                    if not india:   # a small country gets a ring so it is findable
                        xs_ = [q[0] for q in pts]; ys_ = [q[1] for q in pts]
                        r = max(max(xs_) - min(xs_), max(ys_) - min(ys_)) / 2 + 22
                        c = ((max(xs_) + min(xs_)) / 2, (max(ys_) + min(ys_)) / 2)
                        ld.ellipse((c[0] - r, c[1] - r, c[0] + r, c[1] + r), outline=GOLD + (255,), width=4)
    lfont = _font(max(14, int(cw / 24)))
    for f in base:
        name = f["properties"]["name"]
        if name in hl and india:
            ring = max(_rings(f["geometry"]), key=len)
            pts = [xy(p) for p in ring]
            c = (sum(q[0] for q in pts) / len(pts), sum(q[1] for q in pts) / len(pts))
            tw_ = ld.textlength(name, font=lfont)
            ld.text((c[0] - tw_ / 2, c[1] - lfont.size / 2), name, font=lfont, fill=CREAM + (255,),
                    stroke_width=3, stroke_fill=NAVY + (255,))
    mask = Image.new("L", frame, 0)
    ImageDraw.Draw(mask).rounded_rectangle((cx0 + 6, cy0 + head, cx0 + cw - 6, cy0 + ch - 6), radius=22, fill=255)
    img.paste(layer, (0, 0), Image.composite(layer, Image.new("RGBA", frame), mask).split()[3])

    title = m["title"] or "WHERE"
    px = max(18, int(head * 0.50))
    font = _font(px)
    while d.textlength(title, font=font) > cw - 36 and px > 18:
        px -= 2
        font = _font(px)
    tw = d.textlength(title, font=font)
    d.text((cx0 + (cw - tw) / 2, cy0 + head * 0.22), title, font=font, fill=CREAM + (255,))
    img.save(out_path)
    return str(out_path)


def _font(px):
    from PIL import ImageFont
    for f in ("/System/Library/Fonts/Supplemental/Arial Bold.ttf", "/System/Library/Fonts/Helvetica.ttc",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"):
        if os.path.exists(f):
            return ImageFont.truetype(f, px)
    return ImageFont.load_default()


def scenes_for(segments):
    """Which clips carry the inset: the two right after the hook (1-based)."""
    n = len(segments or [])
    return {2, 3} if n >= 4 else ({2} if n >= 2 else {1})
